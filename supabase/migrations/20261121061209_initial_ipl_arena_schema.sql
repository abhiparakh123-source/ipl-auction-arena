-- Initial durable PostgreSQL schema for IPL Auction Arena.
-- Applied to Supabase project iuhclewdjjgahihureqw as migration
-- 20261121061209_initial_ipl_arena_schema.
-- The application connects server-side; no anon/authenticated grants are added.

CREATE TABLE users (
  id text PRIMARY KEY,
  username text NOT NULL,
  pass text NOT NULL,
  salt text NOT NULL,
  created bigint NOT NULL,
  avatar text,
  bio text,
  privacy text DEFAULT 'friends',
  xp integer DEFAULT 0,
  settings text DEFAULT '{}',
  guest smallint DEFAULT 0
);
CREATE UNIQUE INDEX users_username_lower_uq ON users (lower(username));

CREATE TABLE tokens (token text PRIMARY KEY, user_id text NOT NULL, created bigint NOT NULL);
CREATE INDEX tokens_user_id_idx ON tokens(user_id);
CREATE TABLE visitors (visitor text PRIMARY KEY, user_id text NOT NULL);
CREATE INDEX visitors_user_id_idx ON visitors(user_id);
CREATE TABLE friends (user_id text NOT NULL, friend_id text NOT NULL, status text NOT NULL, created bigint, PRIMARY KEY(user_id, friend_id));
CREATE INDEX friends_friend_id_idx ON friends(friend_id);
CREATE TABLE invites (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, from_id text, to_id text, room_code text, created bigint, seen smallint DEFAULT 0);
CREATE INDEX invites_to_id_id_idx ON invites(to_id, id DESC);
CREATE TABLE rooms (code text PRIMARY KEY, state text NOT NULL, updated bigint, host_id text, mode text, public smallint DEFAULT 0, status text, name text);
CREATE INDEX rooms_status_idx ON rooms(status);
CREATE TABLE room_members (code text NOT NULL, user_id text NOT NULL, PRIMARY KEY(code, user_id));
CREATE INDEX room_members_user_id_idx ON room_members(user_id);
CREATE TABLE audit (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text, ts bigint, actor text, action text, data text);
CREATE INDEX audit_code_id_idx ON audit(code, id DESC);
CREATE TABLE achievements (user_id text NOT NULL, key text NOT NULL, ts bigint, room text, PRIMARY KEY(user_id, key));
CREATE TABLE player_overrides (pid text PRIMARY KEY, data text NOT NULL, updated bigint, by text);
CREATE TABLE custom_players (pid text PRIMARY KEY, data text NOT NULL, created bigint, by text);
CREATE TABLE watchlist (user_id text NOT NULL, pid text NOT NULL, note text, PRIMARY KEY(user_id, pid));
CREATE TABLE leagues (id text PRIMARY KEY, name text NOT NULL, owner text NOT NULL, members text NOT NULL, created bigint, code text);
CREATE UNIQUE INDEX leagues_code_uq ON leagues(code) WHERE code IS NOT NULL;
CREATE TABLE scenarios (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id text, code text, data text, created bigint);
CREATE INDEX scenarios_user_id_id_idx ON scenarios(user_id, id DESC);
CREATE TABLE careers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id text, pid text, data text, created bigint);
CREATE INDEX careers_user_id_id_idx ON careers(user_id, id DESC);
CREATE TABLE custom_tournaments (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id text, data text, created bigint);
CREATE INDEX custom_tournaments_user_id_id_idx ON custom_tournaments(user_id, id DESC);
CREATE TABLE matches (code text NOT NULL, season integer NOT NULL, n integer NOT NULL, data text NOT NULL, PRIMARY KEY(code, season, n));
CREATE TABLE game_records (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code text, season integer, kind text, value double precision, pid text, team text, owner text, label text, ts bigint);
CREATE INDEX game_records_value_idx ON game_records(value DESC);
CREATE INDEX game_records_kind_ts_idx ON game_records(kind, ts DESC);

